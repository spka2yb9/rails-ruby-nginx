/* 「パイプ」「Ctrl+C」のように、コマンド名ではない見出しの項目を拾う */
var BY_TOPIC = [
  [/パイプ|リダイレクト|\bpipe\b/, 'pipe'],
  [/Ctrl\+C|シグナル/, 'kill'],
  [/symbolic ?link|シンボリックリンク|Capistrano/, 'ln'],
  [/permission|パーミッション|権限/, 'chmod'],
  [/環境変数/, 'env'],
  [/バックアップ/, 'touch'],
  [/inode/, 'df'],
  [/swap|メモリ/, 'free']
];

var INDEX = {};
C.forEach(function (e) { (e.names || [e.id]).forEach(function (n) { INDEX[n] = e; }); });

/* learn項目 → 解説。cmd の先頭語、次に name の語で引く */
function find(item) {
  if (!item) return null;
  var name = String(item.name || '');
  for (var t = 0; t < BY_TOPIC.length; t++) {
    if (BY_TOPIC[t][0].test(name)) return INDEX[BY_TOPIC[t][1]] || null;
  }
  /* 先頭の sudo と、変数への代入（TG=$(aws ...)）は外して見る */
  var cmd = String(item.cmd || '').trim().replace(/^sudo\s+/, '').replace(/^\w+=\$\(/, '');
  var parts = cmd.split(/[\s|(]+/);
  var first = parts[0];
  /* aws は2語目（ecs / logs / ecr / elbv2）で項目を分ける。無ければ aws（Session Manager）の項 */
  /* Parameter Store と、セキュリティグループの操作は、Session Manager（aws ssm）や EC2 の一覧（aws ec2）と分ける */
  if (first === 'aws' && parts[1] === 'ssm' && /parameter/.test(parts[2] || '')) return INDEX['aws ssm-parameters'];
  if (first === 'aws' && parts[1] === 'ec2' && /security-group/.test(parts[2] || '')) return INDEX['aws ec2-security-groups'];
  if (first === 'aws' && INDEX['aws ' + parts[1]]) return INDEX['aws ' + parts[1]];
  if (INDEX[first]) return INDEX[first];

  var words = String(item.name || '').split(/[\s/（）()]+/);
  for (var i = 0; i < words.length; i++) {
    if (INDEX[words[i]]) return INDEX[words[i]];
  }
  /* rails consoleの式（Entry.where(...) など）は rails の項へ */
  if (/^[A-Z]\w*\./.test(cmd)) return INDEX.rails || null;
  return null;
}

function render(e) {
  var esc = window.LFR.esc, t2h = window.LFR.text2html;
  var html = '<details class="deep"><summary>' +
    '<span class="deep-label">もっと詳しく</span>' +
    '<span class="deep-sub">仕組み・落とし穴・現場での使い方</span></summary>' +
    '<div class="deep-body">';

  html += '<p class="deep-what">' + esc(e.what) + '</p>';
  if (e.how)  html += '<h5>仕組み</h5><div class="prose small">' + t2h(e.how) + '</div>';
  if (e.opts && e.opts.length) {
    html += '<h5>覚えておくオプション</h5><table class="deep-opts"><tbody>' +
      e.opts.map(function (o) {
        return '<tr><th><code>' + esc(o[0]) + '</code></th><td>' + t2h(o[1]) + '</td></tr>';
      }).join('') + '</tbody></table>';
  }
  if (e.gotcha) html += '<h5 class="warn">落とし穴</h5><div class="prose small">' + t2h(e.gotcha) + '</div>';
  if (e.pro)    html += '<h5 class="pro">現場での使い方</h5><div class="prose small">' + t2h(e.pro) + '</div>';

  html += '</div></details>';
  return html;
}

